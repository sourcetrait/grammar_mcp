/// The kind of a nushell `ParseWarning`, one per variant.
#[cereal::derived(Data, Copy, Eq, Hash)]
pub enum ParseWarningKind {
    Deprecated,
}

impl ParseWarningKind {
    /// The diagnostic code nushell gives the kind, where it gives one.
    pub const fn code(self) -> Option<&'static str> {
        match self {
            Self::Deprecated => Some("nu::parser::deprecated"),
        }
    }

    /// The kind's message, the same for every error of the kind.
    pub const fn message(self) -> &'static str {
        match self {
            Self::Deprecated => "Deprecated.",
        }
    }
}

#[cfg(feature = "nushell")]
impl From<&nu::ParseWarning> for ParseWarningKind {
    fn from(v: &nu::ParseWarning) -> Self {
        match v {
            nu::ParseWarning::Deprecated { .. } => Self::Deprecated,
        }
    }
}
