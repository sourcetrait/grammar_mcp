/// The kind of a nushell `ShellWarning`, one per variant.
#[cereal::derived(Data, Copy, Eq, Hash)]
pub enum ShellWarningKind {
    Deprecated,
    InvalidConfig,
    LastResultTruncated,
}

impl ShellWarningKind {
    /// The diagnostic code nushell gives the kind, where it gives one.
    pub const fn code(self) -> Option<&'static str> {
        match self {
            Self::Deprecated => Some("nu::shell::deprecated"),
            Self::InvalidConfig => Some("nu::shell::invalid_config"),
            Self::LastResultTruncated => Some("nu::shell::last_result_truncated"),
        }
    }

    /// The kind's message, the same for every error of the kind.
    pub const fn message(self) -> &'static str {
        match self {
            Self::Deprecated => "Deprecated.",
            Self::InvalidConfig => "Encountered warnings when updating config",
            Self::LastResultTruncated => "Last result was truncated to fit $env.config.max_last_result_size.",
        }
    }
}

#[cfg(feature = "nushell")]
impl From<&nu::ShellWarning> for ShellWarningKind {
    fn from(v: &nu::ShellWarning) -> Self {
        #[allow(deprecated)]
        match v {
            nu::ShellWarning::Deprecated { .. } => Self::Deprecated,
            nu::ShellWarning::InvalidConfig { .. } => Self::InvalidConfig,
            nu::ShellWarning::LastResultTruncated { .. } => Self::LastResultTruncated,
        }
    }
}
